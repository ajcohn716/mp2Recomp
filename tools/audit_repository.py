#!/usr/bin/env python3
"""Audit exactly the staged Git content intended for this source-only repo."""
import subprocess
import sys

# Deliberately enumerate the reviewed publication surface. No broad glob may
# accidentally admit a ROM, asset, dependency checkout, or generated code.
ALLOWED = {
    ".gitignore",
    "install.py",
    ".github/workflows/build.yml",
    ".github/workflows/release.yml",
    "tools/dependency-environment.yml",
    "src/fiber.hpp",
    "src/mingw_compat.hpp",
    "src/self_test.cpp",
    "tests/portability_stubs.cpp",
    "tests/fixture_funcs.h",
    "tests/fixture_overlays.inl",
    "tools/installer-requirements.txt",
    "tools/dependency_pack.py",
    "tools/regenerate.py",
    "tools/build_dependency_pack.py",
    "tools/installer_gui.py",
    "tools/package_installer.py",
    "tests/test_installer.py",
    "CMakeLists.txt",
    "cmake/MinGWCompat.cmake",
    "README.md",
    "aspMain.toml",
    "dependencies.json",
    "mp2.toml",
    "run.sh",
    "src/guest_memory.hpp",
    "src/main.cpp",
    "src/settings.cpp",
    "src/settings.hpp",
    "src/overlays.cpp",
    "src/platform.cpp",
    "src/process.cpp",
    "src/renderer.cpp",
    "tools/audit_repository.py",
    "tools/bootstrap.py",
    "tools/test_settings.sh",
    "tests/settings_test.cpp",
    "tools/generate_symbols.py",
    "tools/regenerate.sh",
}

def git(*args):
    return subprocess.check_output(["git", *args])

def main():
    problems = []
    entries = git("ls-files", "--stage", "-z").split(b"\0")
    count = size = 0
    for entry in entries:
        if not entry:
            continue
        metadata, raw_path = entry.split(b"\t", 1)
        mode, object_id, stage = metadata.decode().split()
        path = raw_path.decode()
        if path not in ALLOWED:
            problems.append(f"{path}: not on the reviewed publication allowlist")
        if mode not in {"100644", "100755"} or stage != "0":
            problems.append(f"{path}: nonregular file, submodule, symlink, or unresolved merge")
            continue
        data = git("cat-file", "blob", object_id)
        count += 1
        size += len(data)
        if len(data) > 64 * 1024:
            problems.append(f"{path}: exceeds 64 KiB source-only limit")
        try:
            content = data.decode("utf-8")
        except UnicodeDecodeError:
            problems.append(f"{path}: binary/non-UTF-8 content")
            continue
        if "\0" in content:
            problems.append(f"{path}: binary NUL byte")
        # Documentation may name these mechanisms without embedding output.
        if path.startswith("src/"):
            for marker in ("RECOMP_FUNC void ", "Generated by spimdisasm", "RspExitReason aspMain(", "/* WARNING: Removing unreachable block", "glabel "):
                if marker in content:
                    problems.append(f"{path}: generated/disassembled code marker {marker!r}")
    if not count:
        problems.append("Git index is empty")
    if problems:
        print("Publication audit FAILED:\n" + "\n".join(problems), file=sys.stderr)
        return 1
    print(f"Publication audit passed: {count} reviewed UTF-8 source/config files, {size:,} bytes.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
